_SUPPORTED_LANGS = tuple(_TRANSLATIONS.keys())


def t(key: str, lang: str = "zh", **kwargs: str) -> str:
    """Look up a translation. Falls back to zh, then to the raw key."""
    text = _TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = _TRANSLATIONS["zh"].get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text


def get_lang(request: Request) -> str:
    """Extract language from Accept-Language header. Defaults to 'zh'."""
    header = request.headers.get("accept-language", "")
    for part in header.split(","):
        tag = part.split(";")[0].strip().lower()
        for supported in _SUPPORTED_LANGS:
            if tag.startswith(supported):
                return supported
    return "zh"
